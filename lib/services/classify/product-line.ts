/**
 * 产品条线判定（C4 客群商机覆盖均衡，2026-09-17）。
 *
 * 问题：商机洞察长期只落在「零售AUM / 中高端 / 普惠小微」三类客群段位上，
 * **按揭 / 信用卡 / 代发** 三条产品线经常 0 条 —— 读者（尤其零售信贷部）看不到自己条线的东西，
 * 但也没人知道「是真没有，还是系统没打标」。
 *
 * 对策（**不动 LLM 提示词、不硬凑条数**）：
 *  - 用确定性的关键词表把条目映射到三条产品线（纯函数、零 token）；
 *  - 覆盖结果**透明展示**：命中给条数，未命中显式标「本期无」——
 *    这正是验收标准的要求（「三类各有 ≥1 条**或明确标注本期无**」）；
 *  - 绝不为了凑覆盖而生成内容：与业务相关性红线冲突（评估文档 §7 明确要求允许「本期无」）。
 *
 * 为什么不做成第 4 个客群段位：段位（`customer-segment.ts`）回答「服务谁」，
 * 产品线回答「卖什么」——两者是**正交**维度，混在一起会让筛选轴互相污染。
 */
export const PRODUCT_LINES = ["按揭", "信用卡", "代发"] as const;
export type ProductLine = (typeof PRODUCT_LINES)[number];

/**
 * 产品线关键词表。
 *
 * 口径说明（刻意保守，宁缺毋滥）：
 *  - 「按揭」只收住房类信贷与楼市交易场景，不收泛指「贷款/信贷」（那是业务线标签的事）；
 *  - 「信用卡」收卡与消费信贷，`分期` 易误伤（分期电商）→ 要求与消费/信用卡/账单共现；
 *  - 「代发」收工资/薪酬/社保代发与对公开户结算（代发是「企业开户 → 代发工资 → 零售获客」链）。
 */
const LINE_RULES: Array<{ line: ProductLine; re: RegExp }> = [
  {
    line: "按揭",
    re: /按揭|房贷|住房贷款|个人住房|开发贷|公积金贷款|首付|二手房|新房成交|楼市|购房|不动产登记/,
  },
  {
    // 「分期」单独出现太泛（分期电商/分期商城）→ 只收组合词（账单分期 / 分期付款）
    line: "信用卡",
    re: /信用卡|消费贷|消费金融|个人消费贷款|信用贷|账单分期|分期付款/,
  },
  {
    line: "代发",
    re: /代发|工资|薪酬|薪资|社保代扣|五险一金|企业开户|对公结算|员工福利|灵活用工|人力资源服务/,
  },
];

/** 文本命中的产品条线（可多值：一条政策可能同时涉及按揭与信用卡）。 */
export function productLinesOf(text: string | undefined): ProductLine[] {
  const t = text ?? "";
  if (!t) return [];
  return LINE_RULES.filter((r) => r.re.test(t)).map((r) => r.line);
}
