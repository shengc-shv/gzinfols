/** 类内命中即取该类权重一次（多词不叠加）；类间相加封顶 100。 */
function sumGroups(groups: CueGroup[], text: string): { score: number; hits: string[] } {
  let score = 0;
  const hits: string[] = [];
  for (const g of groups) {
    if (g.re.test(text)) {
      score += g.weight;
      hits.push(g.name);
    }
  }
  return { score: Math.min(100, score), hits };
}

/**
 * 双视角打分。输入只用 title/summary/subcategory —— 与 `scoreBranchRelevance` 同口径，
 * 因此在 SKIP_AI（无 AI 富化）下也能工作。
 */
export function scoreDualPerspective(a: DualScorable): DualPerspective {
  const text = [a.title, a.summary ?? "", a.subcategory ?? ""].join(" ");
  const m = sumGroups(MACRO_GROUPS, text);
  const b = sumGroups(BIZ_GROUPS, text);
  return {
    macro: m.score,
    biz: b.score,
    macroSignals: m.hits,
    bizSignals: b.hits,
    dual: m.score >= DUAL_THRESHOLD && b.score >= DUAL_THRESHOLD,
  };
}
