/**
 * 双视角打分（2026-10-23 sc 授权）：同一批素材分别按「宏观视角」与「商机视角」打分，
 * 两个榜单独立选优 —— 撤销 2026-10-04 的「商机与必读同 URL 互斥」。
 *
 * 背景（10-23 线上事故）：LLM 把「债基限购」「理财规模」等**既是市场信号又是落地商机**
 * 的素材同时写进 must_read 与 insights，触发互斥规则后**商机侧被单边剔除**（6 → 1 条），
 * 口播稿却仍讲 5~6 条（口播不走该过滤）→ 卡片与口播双重失真。
 *
 * sc 定位（原话）：这两个板块不是「两类内容」，而是**同一批事实的两个解读视角**——
 *   must_read 回答「市场/政策在怎么变」（行长视角）
 *   insights 回答「客群/产品在怎么动」（部门视角）
 * 因此同一事件**可以双呈现**：卡片两个侧面，口播各念各自侧面（不重复念事实）。
 *
 * 设计约束（沿用 relevance-score 的老规矩，全部踩过坑）：
 *  - 纯函数、确定性、可单测；不依赖 LLM 标签；
 *  - 泛化词必须配对（「亿」必须带数字前缀，防「47亿分手费」）；
 *  - 高危短词加否定断言（「客户端」不是「客户」）；
 *  - 类内多词命中**不叠加**（取该类权重一次）—— 防词海战术刷分；
 *  - 类间相加封顶 100。
 */

export interface DualPerspective {
  /** 宏观视角分 0-100（政策/监管/总量/市场趋势） */
  macro: number;
  /** 商机视角分 0-100（客群/产品/资金行为） */
  biz: number;
  /** 命中的宏观类名（可解释） */
  macroSignals: string[];
  /** 命中的商机类名（可解释） */
  bizSignals: string[];
  /** 两维均 ≥ DUAL_THRESHOLD → 建议双呈现 */
  dual: boolean;
}

export interface DualScorable {
  title: string;
  summary?: string;
  subcategory?: string;
}

/** 两维均达到此分即视为「双视角素材」（卡片双呈现、口播各念一面）。
 *  定 25 的理由：「总量数据」类权重即 25 —— 「理财规模超 35 万亿」这类
 *  宏观侧只吃一个总量词（25），但商机侧明确（理财 40+），必须能双呈现。 */
export const DUAL_THRESHOLD = 25;

