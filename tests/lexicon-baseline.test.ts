/** 命中的业务线（从 signals 里取，形如 `业务线[信贷/财富] 权重1`）。 */
function linesOf(title: string): string {
  const sig = (scoreBranchRelevance({ title }).signals ?? []).find((s) => s.startsWith("业务线"));
  return sig ? sig.replace(/^业务线\[|\].*$/g, "") : "";
}

