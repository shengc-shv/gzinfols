const toInsights = (rows: Row[]) => rows.map(([group, topic, impact]) => ({ group, topic, impact }));

for (const [date, rows] of Object.entries(SAMPLES)) {
  test(`商机口播 ${date}：${rows.length} 条最终卡片全部点名（不超预算）`, () => {
    const insights = toInsights(rows);
    const groups = groupInsightsForSpeech(insights);
    const spoken = groupedInsightsSpeech(insights);
    assert.equal(
      groups.reduce((n, g) => n + g.topics.length, 0),
      rows.length,
      "派生组内的主题总数应等于最终卡片条数，不得被概括掉",
    );
    for (const [, topic] of rows) {
      assert.ok(spoken.includes(topic), `「${topic}」没进口播：${spoken}`);
    }
    assert.ok(!/等\d+条线索/.test(spoken), "不得再用「等N条线索」把 1 条说成 N 条");
    assert.ok(
      spoken.length <= AUDIO_SPEAK_LIMITS.insights,
      `派生稿 ${spoken.length} 字超出商机段 ${AUDIO_SPEAK_LIMITS.insights} 字预算`,
    );
  });
}

